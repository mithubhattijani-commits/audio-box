import 'dart:convert';
import 'dart:io';

import 'package:path_provider/path_provider.dart';

import '../models/audio_item.dart';
import '../models/tts_voice.dart';
import 'audio_convert_service.dart';
import 'tts_service.dart';

/// On-device library of generated audios: files in the app documents dir
/// + a small JSON index. Nothing leaves the device.
///
/// MP3 CONVERTER (v1 approach — see README): there is no light on-device
/// WAV→MP3 encoder, so "convert to MP3" re-generates the SAME text via
/// the proxy's Edge endpoint, which returns real MP3 bytes. The result is
/// a genuine MP3 of the same words (Edge voice of the same gender).
/// Cost: the conversion itself is free (Edge voices are free); it is
/// limited to 550 chars per part, so long texts convert into parts.
class AudioLibraryService {
  static const String _indexFileName = 'audio_index.json';

  List<AudioItem> _items = [];
  bool _loaded = false;

  List<AudioItem> get items => List.unmodifiable(_items);

  Future<Directory> _docsDir() async {
    final dir = await getApplicationDocumentsDirectory();
    final audioDir = Directory('${dir.path}/my_audio');
    if (!await audioDir.exists()) await audioDir.create(recursive: true);
    return audioDir;
  }

  Future<File> _indexFile() async {
    final dir = await _docsDir();
    return File('${dir.path}/$_indexFileName');
  }

  Future<void> load() async {
    if (_loaded) return;
    try {
      final file = await _indexFile();
      if (await file.exists()) {
        final raw = jsonDecode(await file.readAsString()) as List;
        _items = raw
            .map((e) => AudioItem.fromJson(e as Map<String, dynamic>))
            .toList();
        // Drop rows whose file was deleted outside the app.
        _items = _items
            .where((i) => File(i.filePath).existsSync())
            .toList();
      }
    } catch (_) {
      _items = [];
    }
    _loaded = true;
  }

  Future<void> _saveIndex() async {
    final file = await _indexFile();
    await file.writeAsString(
      jsonEncode(_items.map((e) => e.toJson()).toList()),
    );
  }

  /// Save generated bytes as a library item. Returns the created item.
  Future<AudioItem> save({
    required String title,
    required String text,
    required TtsVoice voice,
    required List<int> bytes,
    required String ext,
    int chunkIndex = 1,
    int chunkCount = 1,
  }) async {
    await load();
    final dir = await _docsDir();
    final id = DateTime.now().millisecondsSinceEpoch.toString();
    final file = File('${dir.path}/$id.$ext');
    await file.writeAsBytes(bytes);
    final item = AudioItem(
      id: id,
      title: title,
      text: text,
      voiceId: voice.id,
      engine: voice.engine.name,
      filePath: file.path,
      ext: ext,
      createdAtMs: DateTime.now().millisecondsSinceEpoch,
      chunkIndex: chunkIndex,
      chunkCount: chunkCount,
    );
    _items.insert(0, item);
    await _saveIndex();
    return item;
  }

  /// Save trimmed/joined bytes as a library item (v1.0.8). Unlike
  /// [save], there is no TTS voice — the file comes from the device,
  /// so voiceId/engine are 'local' and the text is empty. Returns the
  /// created item.
  Future<AudioItem> saveFile({
    required String title,
    required List<int> bytes,
    required String ext,
  }) async {
    await load();
    final dir = await _docsDir();
    final id = DateTime.now().millisecondsSinceEpoch.toString();
    final file = File('${dir.path}/$id.$ext');
    await file.writeAsBytes(bytes);
    final item = AudioItem(
      id: id,
      title: title,
      text: '',
      voiceId: 'local',
      engine: 'local',
      filePath: file.path,
      ext: ext,
      createdAtMs: DateTime.now().millisecondsSinceEpoch,
    );
    _items.insert(0, item);
    await _saveIndex();
    return item;
  }

  Future<void> delete(AudioItem item) async {
    await load();
    try {
      final f = File(item.filePath);
      if (await f.exists()) await f.delete();
    } catch (_) {}
    _items.removeWhere((i) => i.id == item.id);
    await _saveIndex();
  }

  /// MP3 conversion: re-generate [item]'s text via the Edge endpoint
  /// (returns MP3). Same-gender Edge voice is used (Asad for male,
  /// Uzma for female). Long texts convert into one MP3 per 550-char part.
  /// Returns the new MP3 items (empty when the source is already MP3).
  Future<List<AudioItem>> convertToMp3(AudioItem item) async {
    await load();
    if (item.ext == 'mp3') return [];
    final sourceVoice = TtsVoice.byId(item.voiceId);
    final edgeVoice = sourceVoice.gender == 'Male'
        ? TtsVoice.byId('asad')
        : TtsVoice.byId('uzma');
    final tts = TtsService();
    final chunks = TtsService.chunkText(item.text, edgeVoice);
    final out = <AudioItem>[];
    for (var i = 0; i < chunks.length; i++) {
      final gen = await tts.generateChunk(chunks[i], edgeVoice);
      // v1.0.11: an Edge failure falls back to Gemini, which returns
      // WAV. This flow saves MP3 items, so normalize a WAV part to
      // MP3 first (rare path — Edge only fails on specific short texts).
      final bytes = gen.ext == 'wav'
          ? await AudioConvertService.transcodeBytesToMp3(
              gen.bytes,
              gen.ext,
            )
          : gen.bytes;
      final saved = await save(
        title: '${item.title} (MP3)',
        text: chunks[i],
        voice: edgeVoice,
        bytes: bytes,
        ext: 'mp3',
        chunkIndex: i + 1,
        chunkCount: chunks.length,
      );
      out.add(saved);
    }
    return out;
  }
}
